(function mergeExtraCatalog() {
  var target = window.BOOKS_SERIES = window.BOOKS_SERIES || [];
  (window.BOOKS_EXTRA_SERIES || []).forEach(function (extra) {
    var existing = null;
    for (var i = 0; i < target.length; i++) {
      if (target[i].id === extra.id) { existing = target[i]; break; }
    }
    if (!existing) {
      target.push(extra);
      return;
    }
    Object.keys(extra).forEach(function (key) {
      if (key !== 'books' && extra[key] != null) existing[key] = extra[key];
    });
    existing.books = existing.books || [];
    (extra.books || []).forEach(function (book) {
      var found = false;
      for (var j = 0; j < existing.books.length; j++) {
        if (existing.books[j].id === book.id) {
          existing.books[j] = Object.assign({}, existing.books[j], book);
          found = true;
          break;
        }
      }
      if (!found) existing.books.push(book);
    });
  });
})();
