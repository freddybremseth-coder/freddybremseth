// Merge assets/books-extra.js and catalog fixes into assets/books-data.js inside
// the build workspace. This makes supplemental titles and placement corrections
// available to prerendering, topic pages, sitemap generation and catalog audits.
import fs from 'fs';
import path from 'path';
import vm from 'vm';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const assets = path.join(root, 'assets');
const dataPath = path.join(assets, 'books-data.js');

const dataJs = fs.readFileSync(dataPath, 'utf8');
const json = dataJs.slice(dataJs.indexOf('['), dataJs.lastIndexOf(']') + 1);
const baseSeries = JSON.parse(json);
const context = { window: { BOOKS_SERIES: baseSeries } };
vm.createContext(context);

for (const name of ['books-extra.js', 'books-catalog-fixes.js']) {
  const file = path.join(assets, name);
  if (!fs.existsSync(file)) continue;
  vm.runInContext(fs.readFileSync(file, 'utf8'), context, { filename: name });
}

const merged = context.window.BOOKS_SERIES || baseSeries;
const header = '/* Build-merged catalog: canonical data + supplemental titles + placement fixes.\n   Generated by scripts/merge-extra-catalog.mjs. */\n';
fs.writeFileSync(dataPath, header + 'window.BOOKS_SERIES = ' + JSON.stringify(merged, null, 2) + ';\n');

const bookCount = merged.reduce((n, s) => n + ((s.books || []).length), 0);
console.log(`Merged catalog: ${merged.length} series, ${bookCount} book entries.`);
