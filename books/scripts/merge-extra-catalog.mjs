// Merge assets/books-extra.js into assets/books-data.js inside the build workspace.
// This keeps the handoff catalog stable in git while making new Supabase-backed
// titles available to every existing build step: prerendering, topic pages,
// sitemap generation and catalog audits.
import fs from 'fs';
import path from 'path';
import vm from 'vm';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const dataPath = path.join(root, 'assets', 'books-data.js');
const extraPath = path.join(root, 'assets', 'books-extra.js');

if (!fs.existsSync(extraPath)) {
  console.log('No books-extra.js found; canonical catalog left unchanged.');
  process.exit(0);
}

const dataJs = fs.readFileSync(dataPath, 'utf8');
const json = dataJs.slice(dataJs.indexOf('['), dataJs.lastIndexOf(']') + 1);
const baseSeries = JSON.parse(json);
const extraJs = fs.readFileSync(extraPath, 'utf8');

const context = { window: { BOOKS_SERIES: baseSeries } };
vm.createContext(context);
vm.runInContext(extraJs, context, { filename: 'books-extra.js' });

const merged = context.window.BOOKS_SERIES || baseSeries;
const header = '/* Build-merged catalog: canonical books-data.js + books-extra.js.\n   Generated by scripts/merge-extra-catalog.mjs. */\n';
fs.writeFileSync(dataPath, header + 'window.BOOKS_SERIES = ' + JSON.stringify(merged, null, 2) + ';\n');

const bookCount = merged.reduce((n, s) => n + ((s.books || []).length), 0);
console.log(`Merged extra catalog: ${merged.length} series, ${bookCount} book entries.`);
